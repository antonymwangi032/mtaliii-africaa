/* ============================================
   MTALIII AFRICA — TANZANIA PHOTO DISPLAY FIX
   Uses the existing photo registry
   ============================================ */

(function () {
  "use strict";

  const country = "Tanzania";
  const prefix = "/images/attractions/tanzania/";

  function normalize(value) {
    return String(value || "")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, " ")
      .trim();
  }

  function applyTanzaniaPhotos() {
    const registry = window.MTALIII_PHOTOS || {};

    const photos = Object.entries(registry)
      .filter(([name, path]) =>
        typeof path === "string" &&
        path.startsWith(prefix)
      );

    if (!photos.length) return;

    const cards = document.querySelectorAll(
      ".destination-card, .attraction-card, .place-card"
    );

    cards.forEach(card => {
      const cardText = normalize(card.textContent);

      const match = photos.find(([name]) =>
        cardText.includes(normalize(name))
      );

      if (!match) return;

      const [name, path] = match;

      const image = card.querySelector("img");

      if (image) {
        image.src = path;
        image.removeAttribute("srcset");
        image.alt = name + ", " + country;
        return;
      }

      const photo = card.querySelector(
        ".destination-image, .attraction-image, .place-image"
      );

      if (photo) {
        photo.style.setProperty(
          "background-image",
          `url("${path}")`,
          "important"
        );
      }
    });
  }

  document.addEventListener(
    "DOMContentLoaded",
    applyTanzaniaPhotos
  );

  const observer = new MutationObserver(() => {
    applyTanzaniaPhotos();
  });

  observer.observe(document.documentElement, {
    childList: true,
    subtree: true
  });

})();

